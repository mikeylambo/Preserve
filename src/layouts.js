// Room layouts: one screen is 22 × 13 tiles (Pip is about 6% of screen height);
// Test Chambers are three screens. Each room lists its intended deaths in order
// (`solution`), which the room bot follows to prove the par (tools/prove.mjs).
// A death target is { at: [x, y] } (the material or death mark covers that cell),
// optionally narrowed by `kind`.
export const LAYOUTS = {};
const L = (id, par, rows, extra = {}) => {
  LAYOUTS[id] = { par, rows, ...extra };
};

